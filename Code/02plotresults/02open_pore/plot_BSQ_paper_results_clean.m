% Plot results used in the paper:
% comparison of squirt-flow, Biot-flow, dynamic,
% and quasi-static solutions for dispersion and attenuation.
%
% Required files:
%   result_BSQ_vn_short.mat
%   Pwave_BSQ.txt
%   Q_BSQ.txt
%
% Required functions:
%   Biot_fast.m

clear;
