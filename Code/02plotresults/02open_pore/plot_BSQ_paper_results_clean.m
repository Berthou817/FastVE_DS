format compact;

%% Load dynamic simulation results

load('result_BSQ_vn_short.mat', 'scale', 'Vx_CM', 'Q1');

dimensionlessFrequencyDynamic = scale(:);
dynamicVelocity = Vx_CM(:);
dynamicAttenuation = Q1(:);

%% Convert dynamic velocity to P-wave modulus

porosity = 0.244713;
rhoSolid = 2700;
rhoFluid = 1040;

rhoBulk = ...
    porosity * rhoFluid + ...
    (1 - porosity) * rhoSolid;

velocityScale = sqrt(1e10 / 2700);

dynamicModulus = ...
    (dynamicVelocity * velocityScale).^2 * ...
    rhoBulk / 1e9;

%% Load quasi-static results

referenceFrequency = 10;

[frequencyQuasiStaticModulus, quasiStaticModulus] = ...
    read_comsol_global_txt('Pwave_BSQ.txt');

[frequencyQuasiStaticQ, quasiStaticAttenuation] = ...
    read_comsol_global_txt('Q_BSQ.txt');

dimensionlessFrequencyQuasiStaticModulus = ...
    frequencyQuasiStaticModulus / referenceFrequency;

dimensionlessFrequencyQuasiStaticQ = ...
    frequencyQuasiStaticQ / referenceFrequency;

%% Material and model parameters

par.phi = porosity;

par.Ks = 36e9;
par.Gs = 44e9;
par.Kf = 4.3e9;

par.rhos = rhoSolid;
par.rhof = rhoFluid;

par.eta = 1.414;

par.H_h = 62.913e9;
par.G_h = 26.484e9;
par.K_h = 0;

par.h = 0.25;
par.b = 4.75;

par.phi_c = 0.024010;
par.phi_st = par.phi - par.phi_c;

par.kappa = 12e-5;
par.tau = 9.231664;

par.G = 1.736e10 * 0.99;
par.Kd = 15.428e9;

par.lsq = 5 * 1.414;

%% Biot-flow analytical solution

dimensionlessFrequencyAnalytical = 10.^(-6:0.1:12);

betaDry = 1 / par.Kd;
betaGrain = 1 / par.Ks;
betaFluid = 1 / par.Kf;

biotAlpha = 1 - betaGrain / betaDry;

skemptenB = ...
    (betaDry - betaGrain) / ...
    (betaDry - betaGrain + ...
    par.phi * (betaFluid - betaGrain));

undrainedBulkModulus = ...
    1 / betaDry / ...
    (1 - skemptenB * biotAlpha);

biotM = ...
    undrainedBulkModulus * ...
    skemptenB / biotAlpha;

rhoTotal = ...
    (1 - par.phi) * par.rhos + ...
    par.phi * par.rhof;

biotVelocity = zeros(size(dimensionlessFrequencyAnalytical));
biotAttenuation = zeros(size(dimensionlessFrequencyAnalytical));
biotModulus = zeros(size(dimensionlessFrequencyAnalytical));

for iFrequency = 1:numel(dimensionlessFrequencyAnalytical)

    currentDimensionlessFrequency = ...
        dimensionlessFrequencyAnalytical(iFrequency);

    viscousCoefficient = ...
        par.eta * ...
        currentDimensionlessFrequency / ...
        par.kappa;

    [biotVelocity(iFrequency), biotAttenuation(iFrequency)] = ...
        Biot_fast( ...
        viscousCoefficient, ...
        par.Kd, ...
        par.G, ...
        par.tau, ...
        par.phi, ...
        biotAlpha, ...
        skemptenB, ...
        biotM, ...
        par.rhof, ...
        rhoTotal, ...
        par.G, ...
        referenceFrequency / (2 * pi));

    biotModulus(iFrequency) = ...
        rhoTotal * biotVelocity(iFrequency)^2 / 1e9;
end

%% Squirt-flow analytical solution

[squirtQualityFactor, squirtModulus] = ...
    squirt_flow_solution( ...
    dimensionlessFrequencyAnalytical, par);

squirtAttenuation = ...
    abs(1 ./ squirtQualityFactor);

squirtModulus = ...
    real(squirtModulus) / 1e9;

