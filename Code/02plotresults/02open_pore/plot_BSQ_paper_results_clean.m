%% Local functions

function [frequency, value] = read_comsol_global_txt(fileName)

    fileID = fopen(fileName, 'r');

    if fileID < 0
        error('Cannot open file: %s', fileName);
    end

    cleanupObject = onCleanup(@() fclose(fileID));

    frequency = [];
    value = [];

    while ~feof(fileID)
        currentLine = strtrim(fgetl(fileID));

        if isempty(currentLine) || startsWith(currentLine, '%')
            continue;
        end

        currentData = sscanf(currentLine, '%f %f');

        if numel(currentData) == 2
            frequency(end+1,1) = currentData(1);
            value(end+1,1) = currentData(2);
        end
    end

    if isempty(frequency)
        error('No valid two-column data were found in %s.', fileName);
    end
end

function [qualityFactor, saturatedModulus] = ...
    squirt_flow_solution(dimensionlessFrequency, par)

    referenceFrequency = 10 / (2 * pi);
    angularFrequency = 2 * pi * referenceFrequency;

    grainBulkModulus = par.Ks;
    grainShearModulus = par.Gs;

    dryBulkModulus = par.Kd;
    dryShearModulus = par.G;

    modifiedFramePModulus = par.H_h;
    modifiedFrameShearModulus = par.G_h;
    modifiedFrameBulkModulus = ...
        modifiedFramePModulus ...
        - 4/3 * modifiedFrameShearModulus;

    fluidBulkModulus = par.Kf;
    fluidViscosity = ...
        par.eta .* dimensionlessFrequency;

    crackAperture = par.h;
    crackRadius = par.b;

    crackPorosity = par.phi_c;
    stiffPorosity = par.phi_st;

    squirtLength = par.lsq;
    squirtAspectRatio = ...
        crackAperture / (2 * squirtLength);

    fluidShearModulus = ...
        1i * angularFrequency .* fluidViscosity;

    layerArgument = ...
        sqrt( ...
        3 * fluidShearModulus ./ ...
        (fluidBulkModulus + ...
        4/3 * fluidShearModulus)) / ...
        squirtAspectRatio;

    effectiveFluidModulus = ...
        fluidBulkModulus ...
        + 4/3 * fluidShearModulus ...
        - (fluidBulkModulus ...
        - 2/3 * fluidShearModulus).^2 ./ ...
        (fluidBulkModulus ...
        + 4/3 * fluidShearModulus) .* ...
        tanh(layerArgument) ./ ...
        layerArgument;

    modifiedFrameBulkModulus = ...
        1 ./ ...
        (1 / modifiedFrameBulkModulus ...
        + 1 ./ ...
        (1 / ...
        (1 / dryBulkModulus ...
        - 1 / modifiedFrameBulkModulus) ...
        + 1 ./ ...
        ((1 ./ effectiveFluidModulus ...
        - 1 / grainBulkModulus) .* ...
        crackPorosity)));

    modifiedFrameShearModulus = ...
        1 ./ ...
        (1 / dryShearModulus ...
        - 4/15 .* ...
        (1 / dryBulkModulus ...
        - 1 ./ modifiedFrameBulkModulus));

    saturatedBulkModulus = ...
        1 ./ ...
        (1 / grainBulkModulus ...
        + stiffPorosity .* ...
        (1 / fluidBulkModulus ...
        - 1 / grainBulkModulus) ./ ...
        (1 + stiffPorosity .* ...
        (1 / fluidBulkModulus ...
        - 1 / grainBulkModulus) ./ ...
        (1 ./ modifiedFrameBulkModulus ...
        - 1 / grainBulkModulus)));

    saturatedShearModulus = ...
        modifiedFrameShearModulus;

    saturatedModulus = ...
        saturatedBulkModulus ...
        + 4/3 * saturatedShearModulus;

    qualityFactor = ...
        real(saturatedModulus) ./ ...
        imag(saturatedModulus);

    unusedGrainPModulus = ...
        grainBulkModulus ...
        + 4/3 * grainShearModulus;

    unusedCrackAspectRatio = ...
        crackAperture / ...
        (2 * crackRadius);

    clear unusedGrainPModulus unusedCrackAspectRatio;
end
